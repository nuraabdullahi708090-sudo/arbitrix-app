-- 038_marketing_broadcast.sql
--
-- Durable queue + audit trail + consent store for the Telegram marketing
-- publisher (services/MarketingWorker.js, marketing-worker.js).
--
-- SCOPE AND SAFETY
--   * Content publishing ONLY. No wallet, ledger, trade, deposit, withdrawal,
--     subscription, referral or sandbox table is read or written here.
--   * RLS is ENABLED on every table and only service_role is granted access, so
--     an anon/authenticated key can neither read the queue nor subscribe a chat.
--   * `telegram_marketing_control` starts PAUSED with dry_run = TRUE. Nothing is
--     ever sent until an administrator explicitly resumes and disables dry-run,
--     which is the safe default for an unattended publisher.
--   * The queue stores the RENDERED text that was validated by the content guard
--     (services/ContentGuard.js) plus the guard result, so an audit shows exactly
--     what was checked and what was approved.
--
-- ADDITIVE AND IDEMPOTENT: every object is created IF NOT EXISTS, and the
-- trailing DO block re-verifies the contract and rolls the whole migration back
-- if anything is missing.

BEGIN;

-- ---------------------------------------------------------------------------
-- 1. Publishing queue
-- ---------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS public.telegram_marketing_posts (
  id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  kind                TEXT        NOT NULL,
  theme               TEXT,
  locale              TEXT        NOT NULL DEFAULT 'en',
  audience            TEXT        NOT NULL DEFAULT 'group',
  chat_id             TEXT,
  content             TEXT        NOT NULL,
  buttons             JSONB       NOT NULL DEFAULT '[]'::jsonb,
  status              TEXT        NOT NULL DEFAULT 'draft',
  idempotency_key     TEXT        NOT NULL UNIQUE,
  scheduled_for       TIMESTAMPTZ,
  attempts            INTEGER     NOT NULL DEFAULT 0,
  max_attempts        INTEGER     NOT NULL DEFAULT 5,
  last_error          TEXT,
  guard               JSONB,
  telegram_message_id BIGINT,
  approved_by         BIGINT,
  approved_at         TIMESTAMPTZ,
  published_at        TIMESTAMPTZ,
  created_by          BIGINT,
  created_at          TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at          TIMESTAMPTZ NOT NULL DEFAULT now()
);

-- Re-assert the invariants even when the table already existed (an earlier
-- partial apply must not be able to weaken them).
ALTER TABLE public.telegram_marketing_posts
  DROP CONSTRAINT IF EXISTS telegram_marketing_posts_locale_check,
  DROP CONSTRAINT IF EXISTS telegram_marketing_posts_audience_check,
  DROP CONSTRAINT IF EXISTS telegram_marketing_posts_status_check;

ALTER TABLE public.telegram_marketing_posts
  ADD CONSTRAINT telegram_marketing_posts_locale_check
    CHECK (locale IN ('en', 'pt', 'ar')),
  ADD CONSTRAINT telegram_marketing_posts_audience_check
    CHECK (audience IN ('group', 'channel', 'subscribers')),
  ADD CONSTRAINT telegram_marketing_posts_status_check
    CHECK (status IN ('draft', 'awaiting_approval', 'approved', 'scheduled',
                      'sending', 'published', 'failed', 'blocked', 'cancelled'));

CREATE INDEX IF NOT EXISTS telegram_marketing_posts_due_idx
  ON public.telegram_marketing_posts (status, scheduled_for)
  WHERE status = 'scheduled';

CREATE INDEX IF NOT EXISTS telegram_marketing_posts_created_idx
  ON public.telegram_marketing_posts (created_at DESC);

-- ---------------------------------------------------------------------------
-- 2. Private-chat marketing consent (opt-in only)
-- ---------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS public.telegram_marketing_subscriptions (
  telegram_chat_id TEXT        PRIMARY KEY,
  telegram_user_id TEXT,
  locale           TEXT        NOT NULL DEFAULT 'en',
  subscribed       BOOLEAN     NOT NULL DEFAULT TRUE,
  consent_source   TEXT,
  created_at       TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at       TIMESTAMPTZ NOT NULL DEFAULT now(),
  unsubscribed_at  TIMESTAMPTZ
);

ALTER TABLE public.telegram_marketing_subscriptions
  DROP CONSTRAINT IF EXISTS telegram_marketing_subscriptions_locale_check;
ALTER TABLE public.telegram_marketing_subscriptions
  ADD CONSTRAINT telegram_marketing_subscriptions_locale_check
    CHECK (locale IN ('en', 'pt', 'ar'));

CREATE INDEX IF NOT EXISTS telegram_marketing_subscriptions_active_idx
  ON public.telegram_marketing_subscriptions (subscribed)
  WHERE subscribed = TRUE;

-- ---------------------------------------------------------------------------
-- 3. Publisher control (singleton). PAUSED + DRY-RUN by default.
-- ---------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS public.telegram_marketing_control (
  id         INTEGER     PRIMARY KEY DEFAULT 1,
  paused     BOOLEAN     NOT NULL DEFAULT TRUE,
  dry_run    BOOLEAN     NOT NULL DEFAULT TRUE,
  updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_by BIGINT
);

ALTER TABLE public.telegram_marketing_control
  DROP CONSTRAINT IF EXISTS telegram_marketing_control_singleton;
ALTER TABLE public.telegram_marketing_control
  ADD CONSTRAINT telegram_marketing_control_singleton CHECK (id = 1);

INSERT INTO public.telegram_marketing_control (id, paused, dry_run)
VALUES (1, TRUE, TRUE)
ON CONFLICT (id) DO NOTHING;

-- ---------------------------------------------------------------------------
-- 4. Per-send audit trail (no secrets, no recipient PII beyond the chat id)
-- ---------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS public.telegram_marketing_sends (
  id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  post_id             BIGINT REFERENCES public.telegram_marketing_posts (id) ON DELETE SET NULL,
  audience            TEXT,
  chat_id             TEXT,
  status              TEXT        NOT NULL,
  attempt             INTEGER,
  telegram_message_id BIGINT,
  error               TEXT,
  created_at          TIMESTAMPTZ NOT NULL DEFAULT now()
);

ALTER TABLE public.telegram_marketing_sends
  DROP CONSTRAINT IF EXISTS telegram_marketing_sends_status_check;
ALTER TABLE public.telegram_marketing_sends
  ADD CONSTRAINT telegram_marketing_sends_status_check
    CHECK (status IN ('sent', 'failed', 'skipped', 'blocked'));

CREATE INDEX IF NOT EXISTS telegram_marketing_sends_post_idx
  ON public.telegram_marketing_sends (post_id, created_at DESC);

-- ---------------------------------------------------------------------------
-- 5. RLS: service_role only (no anon / authenticated policy = deny by default)
-- ---------------------------------------------------------------------------
ALTER TABLE public.telegram_marketing_posts           ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.telegram_marketing_subscriptions   ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.telegram_marketing_control         ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.telegram_marketing_sends           ENABLE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS marketing_posts_service_all ON public.telegram_marketing_posts;
CREATE POLICY marketing_posts_service_all ON public.telegram_marketing_posts
  FOR ALL TO service_role USING (true) WITH CHECK (true);

DROP POLICY IF EXISTS marketing_subs_service_all ON public.telegram_marketing_subscriptions;
CREATE POLICY marketing_subs_service_all ON public.telegram_marketing_subscriptions
  FOR ALL TO service_role USING (true) WITH CHECK (true);

DROP POLICY IF EXISTS marketing_control_service_all ON public.telegram_marketing_control;
CREATE POLICY marketing_control_service_all ON public.telegram_marketing_control
  FOR ALL TO service_role USING (true) WITH CHECK (true);

DROP POLICY IF EXISTS marketing_sends_service_all ON public.telegram_marketing_sends;
CREATE POLICY marketing_sends_service_all ON public.telegram_marketing_sends
  FOR ALL TO service_role USING (true) WITH CHECK (true);

REVOKE ALL ON public.telegram_marketing_posts         FROM PUBLIC, anon, authenticated;
REVOKE ALL ON public.telegram_marketing_subscriptions FROM PUBLIC, anon, authenticated;
REVOKE ALL ON public.telegram_marketing_control       FROM PUBLIC, anon, authenticated;
REVOKE ALL ON public.telegram_marketing_sends         FROM PUBLIC, anon, authenticated;

GRANT SELECT, INSERT, UPDATE, DELETE ON public.telegram_marketing_posts         TO service_role;
GRANT SELECT, INSERT, UPDATE, DELETE ON public.telegram_marketing_subscriptions TO service_role;
GRANT SELECT, INSERT, UPDATE, DELETE ON public.telegram_marketing_control       TO service_role;
GRANT SELECT, INSERT, UPDATE, DELETE ON public.telegram_marketing_sends         TO service_role;
GRANT USAGE, SELECT ON ALL SEQUENCES IN SCHEMA public TO service_role;

-- ---------------------------------------------------------------------------
-- 6. Atomic claim (FOR UPDATE SKIP LOCKED so two workers never send one post)
-- ---------------------------------------------------------------------------
CREATE OR REPLACE FUNCTION public.claim_marketing_posts(
  p_now   TIMESTAMPTZ,
  p_limit INTEGER DEFAULT 5
)
RETURNS SETOF public.telegram_marketing_posts
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
  v_limit INTEGER := LEAST(GREATEST(COALESCE(p_limit, 5), 1), 25);
BEGIN
  RETURN QUERY
  WITH due AS (
    SELECT p.id
    FROM public.telegram_marketing_posts p
    WHERE p.status = 'scheduled'
      AND p.scheduled_for IS NOT NULL
      AND p.scheduled_for <= COALESCE(p_now, now())
      AND p.attempts < p.max_attempts
    ORDER BY p.scheduled_for ASC
    LIMIT v_limit
    FOR UPDATE SKIP LOCKED
  )
  UPDATE public.telegram_marketing_posts p
  SET status = 'sending',
      attempts = p.attempts + 1,
      updated_at = now()
  FROM due
  WHERE p.id = due.id
  RETURNING p.*;
END;
$$;

-- ---------------------------------------------------------------------------
-- 7. Terminal transitions (idempotent: only acts on a 'sending' row)
-- ---------------------------------------------------------------------------
CREATE OR REPLACE FUNCTION public.finish_marketing_post(
  p_id         BIGINT,
  p_ok         BOOLEAN,
  p_message_id BIGINT DEFAULT NULL,
  p_error      TEXT DEFAULT NULL,
  p_retry_at   TIMESTAMPTZ DEFAULT NULL
)
RETURNS public.telegram_marketing_posts
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
  v_row public.telegram_marketing_posts;
BEGIN
  IF p_id IS NULL THEN
    RAISE EXCEPTION 'post id is required';
  END IF;

  IF p_ok THEN
    UPDATE public.telegram_marketing_posts
    SET status = 'published',
        telegram_message_id = COALESCE(p_message_id, telegram_message_id),
        published_at = now(),
        last_error = NULL,
        updated_at = now()
    WHERE id = p_id AND status = 'sending'
    RETURNING * INTO v_row;
  ELSE
    UPDATE public.telegram_marketing_posts
    SET status = CASE WHEN attempts >= max_attempts THEN 'failed' ELSE 'scheduled' END,
        scheduled_for = CASE WHEN attempts >= max_attempts THEN scheduled_for
                             ELSE COALESCE(p_retry_at, now() + interval '2 minutes') END,
        last_error = left(COALESCE(p_error, 'unknown error'), 500),
        updated_at = now()
    WHERE id = p_id AND status = 'sending'
    RETURNING * INTO v_row;
  END IF;

  RETURN v_row;
END;
$$;

CREATE OR REPLACE FUNCTION public.block_marketing_post(
  p_id     BIGINT,
  p_reason TEXT
)
RETURNS public.telegram_marketing_posts
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
  v_row public.telegram_marketing_posts;
BEGIN
  UPDATE public.telegram_marketing_posts
  SET status = 'blocked',
      last_error = left(COALESCE(p_reason, 'blocked by content guard'), 500),
      updated_at = now()
  WHERE id = p_id AND status IN ('scheduled', 'sending', 'approved')
  RETURNING * INTO v_row;
  RETURN v_row;
END;
$$;

REVOKE ALL ON FUNCTION public.claim_marketing_posts(TIMESTAMPTZ, INTEGER) FROM PUBLIC, anon, authenticated;
REVOKE ALL ON FUNCTION public.finish_marketing_post(BIGINT, BOOLEAN, BIGINT, TEXT, TIMESTAMPTZ) FROM PUBLIC, anon, authenticated;
REVOKE ALL ON FUNCTION public.block_marketing_post(BIGINT, TEXT) FROM PUBLIC, anon, authenticated;

GRANT EXECUTE ON FUNCTION public.claim_marketing_posts(TIMESTAMPTZ, INTEGER) TO service_role;
GRANT EXECUTE ON FUNCTION public.finish_marketing_post(BIGINT, BOOLEAN, BIGINT, TEXT, TIMESTAMPTZ) TO service_role;
GRANT EXECUTE ON FUNCTION public.block_marketing_post(BIGINT, TEXT) TO service_role;

-- ---------------------------------------------------------------------------
-- 8. Self-check: roll the whole migration back if the contract is not met
-- ---------------------------------------------------------------------------
DO $$
DECLARE
  v_missing TEXT[] := ARRAY[]::TEXT[];
  v_table   TEXT;
BEGIN
  FOREACH v_table IN ARRAY ARRAY[
    'telegram_marketing_posts',
    'telegram_marketing_subscriptions',
    'telegram_marketing_control',
    'telegram_marketing_sends'
  ] LOOP
    IF to_regclass('public.' || v_table) IS NULL THEN
      v_missing := array_append(v_missing, 'table ' || v_table);
    ELSIF NOT (SELECT relrowsecurity FROM pg_class WHERE oid = to_regclass('public.' || v_table)) THEN
      v_missing := array_append(v_missing, 'RLS on ' || v_table);
    END IF;
  END LOOP;

  IF NOT EXISTS (SELECT 1 FROM public.telegram_marketing_control WHERE id = 1) THEN
    v_missing := array_append(v_missing, 'control row');
  END IF;

  IF to_regprocedure('public.claim_marketing_posts(timestamptz,integer)') IS NULL THEN
    v_missing := array_append(v_missing, 'function claim_marketing_posts');
  END IF;
  IF to_regprocedure('public.finish_marketing_post(bigint,boolean,bigint,text,timestamptz)') IS NULL THEN
    v_missing := array_append(v_missing, 'function finish_marketing_post');
  END IF;
  IF to_regprocedure('public.block_marketing_post(bigint,text)') IS NULL THEN
    v_missing := array_append(v_missing, 'function block_marketing_post');
  END IF;

  IF array_length(v_missing, 1) IS NOT NULL THEN
    RAISE EXCEPTION 'migration 038 incomplete: %', array_to_string(v_missing, ', ');
  END IF;
END;
$$;

COMMIT;
