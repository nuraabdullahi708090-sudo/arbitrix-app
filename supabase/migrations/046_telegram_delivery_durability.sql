-- 046_telegram_delivery_durability.sql
--
-- Two reliability gaps in the Telegram automation, both closed additively.
--
-- WHY
--   1. The admin status route could only report the WEB service's destination
--      configuration. The publisher runs as a separate process with its own
--      environment, so an operator reading `channelConfigured: false` had no way
--      to tell "the worker has no channel id" from "only this service lacks it".
--      The worker already computes those flags at boot; this persists them with
--      the heartbeat so one status call shows the WORKER's view.
--   2. The join-welcome de-duplication lived in process memory, so a Render
--      restart or a Telegram redelivery after a restart could greet the same
--      member twice. This adds a durable delivery ledger the onboarding code
--      consults before sending (and releases if the send fails).
--
-- WHAT
--   * telegram_marketing_control gains three nullable worker columns:
--       worker_group_configured     BOOLEAN
--       worker_channel_configured   BOOLEAN
--       worker_config_warning       TEXT
--   * new table public.telegram_welcome_deliveries(chat_id, member_id,
--       message_id, created_at) with UNIQUE (chat_id, member_id, message_id).
--     message_id is NOT NULL DEFAULT '' so the unique index is a plain column
--     index (PostgREST can then use onConflict).
--
-- SAFETY
--   * Additive and idempotent. NULL worker columns mean "not reported yet", so an
--     existing deployment stays healthy-but-unknown rather than broken.
--   * No permission change on the control row: service_role already holds UPDATE
--     and the 038 policy is untouched. Writing a heartbeat can still never change
--     paused or dry_run.
--   * The ledger stores chat/member/message ids only - no message body, no
--     token, no PII beyond Telegram ids, and nothing financial.
--   * Both features fail OPEN in the application: if this migration is not
--     applied, the publisher keeps publishing and the welcome keeps working with
--     the previous in-memory de-duplication.
--
-- The trailing DO block re-verifies the contract and rolls the file back if any
-- object is missing.

BEGIN;

-- ---------------------------------------------------------------------------
-- 1. Worker-reported destination state
-- ---------------------------------------------------------------------------
ALTER TABLE public.telegram_marketing_control
  ADD COLUMN IF NOT EXISTS worker_group_configured   BOOLEAN;

ALTER TABLE public.telegram_marketing_control
  ADD COLUMN IF NOT EXISTS worker_channel_configured BOOLEAN;

ALTER TABLE public.telegram_marketing_control
  ADD COLUMN IF NOT EXISTS worker_config_warning     TEXT;

COMMENT ON COLUMN public.telegram_marketing_control.worker_group_configured IS
  'Group destination as resolved BY THE WORKER PROCESS (not the web service).';
COMMENT ON COLUMN public.telegram_marketing_control.worker_channel_configured IS
  'Channel destination as resolved BY THE WORKER PROCESS. false here with true on the web service means TELEGRAM_ANNOUNCEMENT_CHAT_ID is missing on the worker.';
COMMENT ON COLUMN public.telegram_marketing_control.worker_config_warning IS
  'Non-secret reason a destination was rejected, e.g. TELEGRAM_ANNOUNCEMENT_CHAT_ID:username-not-supported.';

-- ---------------------------------------------------------------------------
-- 2. Durable welcome delivery ledger
-- ---------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS public.telegram_welcome_deliveries (
  id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  chat_id    TEXT        NOT NULL,
  member_id  TEXT        NOT NULL,
  message_id TEXT        NOT NULL DEFAULT '',
  created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE UNIQUE INDEX IF NOT EXISTS telegram_welcome_deliveries_key
  ON public.telegram_welcome_deliveries (chat_id, member_id, message_id);

CREATE INDEX IF NOT EXISTS telegram_welcome_deliveries_created_at
  ON public.telegram_welcome_deliveries (created_at);

ALTER TABLE public.telegram_welcome_deliveries ENABLE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS welcome_deliveries_service_all ON public.telegram_welcome_deliveries;
CREATE POLICY welcome_deliveries_service_all ON public.telegram_welcome_deliveries
  FOR ALL TO service_role USING (true) WITH CHECK (true);

REVOKE ALL ON public.telegram_welcome_deliveries FROM PUBLIC;
REVOKE ALL ON public.telegram_welcome_deliveries FROM anon;
REVOKE ALL ON public.telegram_welcome_deliveries FROM authenticated;
GRANT ALL ON public.telegram_welcome_deliveries TO service_role;

COMMENT ON TABLE public.telegram_welcome_deliveries IS
  'Which join service messages have already been welcomed, so a restart cannot greet the same member twice. Ids only - never message text.';

-- ---------------------------------------------------------------------------
-- 3. Self-check (inside the transaction: any failure rolls the file back)
-- ---------------------------------------------------------------------------
DO $verify$
DECLARE
  v_cols INTEGER;
BEGIN
  SELECT count(*) INTO v_cols
  FROM information_schema.columns
  WHERE table_schema = 'public'
    AND table_name = 'telegram_marketing_control'
    AND column_name IN ('worker_group_configured', 'worker_channel_configured', 'worker_config_warning');

  IF v_cols <> 3 THEN
    RAISE EXCEPTION '046 self-check: expected 3 worker columns on telegram_marketing_control, found %', v_cols;
  END IF;

  IF NOT EXISTS (
    SELECT 1 FROM pg_class c
    JOIN pg_namespace n ON n.oid = c.relnamespace
    WHERE n.nspname = 'public' AND c.relname = 'telegram_welcome_deliveries' AND c.relkind = 'r'
  ) THEN
    RAISE EXCEPTION '046 self-check: telegram_welcome_deliveries table is missing';
  END IF;

  IF NOT EXISTS (
    SELECT 1 FROM pg_indexes
    WHERE schemaname = 'public'
      AND tablename = 'telegram_welcome_deliveries'
      AND indexname = 'telegram_welcome_deliveries_key'
  ) THEN
    RAISE EXCEPTION '046 self-check: the unique welcome key index is missing';
  END IF;

  IF NOT EXISTS (
    SELECT 1 FROM pg_policies
    WHERE schemaname = 'public'
      AND tablename = 'telegram_welcome_deliveries'
      AND policyname = 'welcome_deliveries_service_all'
  ) THEN
    RAISE EXCEPTION '046 self-check: the service_role policy is missing';
  END IF;

  IF NOT EXISTS (
    SELECT 1 FROM public.telegram_marketing_control WHERE id = 1
  ) THEN
    RAISE EXCEPTION '046 self-check: the singleton control row (id = 1) is missing';
  END IF;
END;
$verify$;

COMMIT;
