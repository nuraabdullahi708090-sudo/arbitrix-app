-- ===========================================================================
-- 058_notifications.sql - durable, event-driven in-app notifications
-- ===========================================================================
--
-- WHAT THIS ADDS
--   1. public.notifications            - the user-facing feed (per account)
--   2. public.notification_emit(...)   - the ONE idempotent insert path
--   3. observational triggers that record the money-side facts the feed must
--      never miss: deposit pending, deposit confirmed, referral reward credited
--
-- WHY TRIGGERS FOR THE MONEY EVENTS
--   The authoritative markers are written in several places (provider credit
--   functions, confirm_legacy_deposit_safe, admin confirmations, the JS
--   referral award). A JS hook would need every call site and would silently
--   miss any path added later. A row trigger fires inside the SAME transaction
--   as the marker write, so a notification exists if and only if the event was
--   committed, and a retried webhook cannot produce a second one.
--   This migration ONLY observes: it never reads or writes balances, wallets,
--   ledger rows, referrals, deposits or invoices.
--
-- DEDUPLICATION
--   notifications.event_key is UNIQUE per user. Every writer (the server and
--   the triggers below) goes through notification_emit(), which does
--   INSERT ... ON CONFLICT (user_id, event_key) DO NOTHING. Retries, duplicate
--   webhooks, concurrent requests and repeated page loads therefore cannot
--   create a second notification for the same business event.
--   Rows are never DELETEd by the Clear control - it sets cleared_at - so a
--   cleared event can never be recreated by the same event key.
--
-- SAFETY POSTURE
--   * Every trigger function catches its own errors and downgrades them to a
--     WARNING, so a problem here can never block a deposit, a credit or a
--     referral award.
--   * MARKETING_SANDBOX users are skipped: their simulated money never produces
--     real account notifications.
--   * Self-referrals and synthetic referral rows (referred_id <= 0) are skipped.
--   * RLS is enabled with a single service_role policy; anon/authenticated get
--     no access at all (same model as 039/040/045).
--
-- ROLLBACK (no money data involved)
--   DROP TRIGGER IF EXISTS notifications_deposit_invoice ON public.payment_invoices;
--   DROP TRIGGER IF EXISTS notifications_deposit_legacy ON public.deposits;
--   DROP TRIGGER IF EXISTS notifications_referral ON public.referrals;
--   DROP FUNCTION IF EXISTS public.notifications_capture_deposit();
--   DROP FUNCTION IF EXISTS public.notifications_capture_referral();
--   DROP FUNCTION IF EXISTS public.notification_emit(BIGINT, TEXT, TEXT, TEXT, TEXT, JSONB);
--   DROP FUNCTION IF EXISTS public.notification_user_is_sandbox(BIGINT);
--   DROP TABLE IF EXISTS public.notifications;
-- ===========================================================================

-- ---------------------------------------------------------------------------
-- 1. The feed
-- ---------------------------------------------------------------------------

CREATE TABLE IF NOT EXISTS public.notifications (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id     BIGINT      NOT NULL REFERENCES public.users (id) ON DELETE CASCADE,
    -- Stable identifier of the BUSINESS event ("welcome", "first_trade",
    -- "deposit_confirmed:invoice:123"). This is the dedupe anchor.
    event_key   TEXT        NOT NULL,
    type        TEXT        NOT NULL DEFAULT 'info',
    -- i18n keys + interpolation values: the feed is rendered in the reader's
    -- current language instead of freezing the language of the event moment.
    title_key   TEXT        NOT NULL,
    body_key    TEXT,
    vars        JSONB       NOT NULL DEFAULT '{}'::jsonb,
    -- The moment the event happened (not the moment the row was read).
    occurred_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    read_at     TIMESTAMPTZ,
    -- Soft clear: keeps the event_key claim so Clear can never resurrect it.
    cleared_at  TIMESTAMPTZ,
    created_at  TIMESTAMPTZ NOT NULL DEFAULT now()
);

ALTER TABLE public.notifications DROP CONSTRAINT IF EXISTS notifications_type_check;
ALTER TABLE public.notifications
    ADD CONSTRAINT notifications_type_check
    CHECK (type IN ('info', 'success', 'warning', 'badge'));

ALTER TABLE public.notifications DROP CONSTRAINT IF EXISTS notifications_event_key_len_check;
ALTER TABLE public.notifications
    ADD CONSTRAINT notifications_event_key_len_check
    CHECK (char_length(event_key) BETWEEN 1 AND 160);

ALTER TABLE public.notifications DROP CONSTRAINT IF EXISTS notifications_user_event_key_key;
ALTER TABLE public.notifications
    ADD CONSTRAINT notifications_user_event_key_key
    UNIQUE (user_id, event_key);

CREATE INDEX IF NOT EXISTS notifications_user_feed_idx
    ON public.notifications (user_id, occurred_at DESC)
    WHERE cleared_at IS NULL;

COMMENT ON TABLE public.notifications IS
    'In-app notification feed. event_key is the business-event identity; UNIQUE(user_id, event_key) makes every writer idempotent. Clear sets cleared_at so an event can never be recreated.';

-- ---------------------------------------------------------------------------
-- 2. Access control (service_role only, like 039 / 040 / 045)
-- ---------------------------------------------------------------------------

ALTER TABLE public.notifications ENABLE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS notifications_service_all ON public.notifications;
CREATE POLICY notifications_service_all ON public.notifications
    FOR ALL TO service_role USING (true) WITH CHECK (true);

REVOKE ALL ON public.notifications FROM PUBLIC;
REVOKE ALL ON public.notifications FROM anon;
REVOKE ALL ON public.notifications FROM authenticated;

-- RLS alone does not grant privileges: the server's service-role client reads
-- and updates the feed through PostgREST, so it needs the table privileges
-- explicitly. No DELETE: Clear is a soft clear, so nothing ever hard-deletes a
-- row (the FK cascade on user deletion is a system-level operation).
GRANT SELECT, INSERT, UPDATE ON public.notifications TO service_role;

DO $$
BEGIN
    IF EXISTS (
        SELECT 1 FROM pg_class c
        JOIN pg_namespace n ON n.oid = c.relnamespace
        WHERE n.nspname = 'public' AND c.relname = 'notifications_id_seq' AND c.relkind = 'S'
    ) THEN
        EXECUTE 'REVOKE ALL ON SEQUENCE public.notifications_id_seq FROM PUBLIC, anon, authenticated';
        EXECUTE 'GRANT USAGE, SELECT ON SEQUENCE public.notifications_id_seq TO service_role';
    END IF;
END $$;

-- ---------------------------------------------------------------------------
-- 3. Helpers
-- ---------------------------------------------------------------------------

-- Reads users.environment defensively: the column arrives with migration 013.
-- A missing column must not break the feed, so it is caught and treated as a
-- production account.
CREATE OR REPLACE FUNCTION public.notification_user_is_sandbox(p_user_id BIGINT)
RETURNS BOOLEAN
LANGUAGE plpgsql
STABLE
SECURITY DEFINER
SET search_path = public, pg_temp
AS $$
DECLARE
    v_env TEXT;
BEGIN
    IF p_user_id IS NULL THEN
        RETURN FALSE;
    END IF;
    BEGIN
        SELECT u.environment INTO v_env FROM public.users u WHERE u.id = p_user_id;
    EXCEPTION WHEN OTHERS THEN
        RETURN FALSE;
    END;
    RETURN COALESCE(v_env, 'PRODUCTION') = 'MARKETING_SANDBOX';
END;
$$;

-- The ONE idempotent insert path. Returns TRUE when a new row was created and
-- FALSE when the event was already recorded (or the write could not happen).
CREATE OR REPLACE FUNCTION public.notification_emit(
    p_user_id   BIGINT,
    p_event_key TEXT,
    p_type      TEXT DEFAULT 'info',
    p_title_key TEXT DEFAULT 'notifications.generic.title',
    p_body_key  TEXT DEFAULT NULL,
    p_vars      JSONB DEFAULT '{}'::jsonb,
    p_occurred_at TIMESTAMPTZ DEFAULT now()
)
RETURNS BOOLEAN
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public, pg_temp
AS $$
DECLARE
    v_inserted INTEGER := 0;
BEGIN
    IF p_user_id IS NULL OR p_event_key IS NULL OR char_length(p_event_key) = 0 THEN
        RETURN FALSE;
    END IF;

    INSERT INTO public.notifications (user_id, event_key, type, title_key, body_key, vars, occurred_at)
    VALUES (
        p_user_id,
        left(p_event_key, 160),
        CASE WHEN p_type IN ('info', 'success', 'warning', 'badge') THEN p_type ELSE 'info' END,
        COALESCE(NULLIF(p_title_key, ''), 'notifications.generic.title'),
        NULLIF(p_body_key, ''),
        COALESCE(p_vars, '{}'::jsonb),
        COALESCE(p_occurred_at, now())
    )
    ON CONFLICT (user_id, event_key) DO NOTHING;

    GET DIAGNOSTICS v_inserted = ROW_COUNT;
    RETURN v_inserted > 0;
END;
$$;

REVOKE ALL ON FUNCTION public.notification_emit(BIGINT, TEXT, TEXT, TEXT, TEXT, JSONB, TIMESTAMPTZ) FROM PUBLIC;
REVOKE ALL ON FUNCTION public.notification_emit(BIGINT, TEXT, TEXT, TEXT, TEXT, JSONB, TIMESTAMPTZ) FROM anon;
REVOKE ALL ON FUNCTION public.notification_emit(BIGINT, TEXT, TEXT, TEXT, TEXT, JSONB, TIMESTAMPTZ) FROM authenticated;
GRANT EXECUTE ON FUNCTION public.notification_emit(BIGINT, TEXT, TEXT, TEXT, TEXT, JSONB, TIMESTAMPTZ) TO service_role;

REVOKE ALL ON FUNCTION public.notification_user_is_sandbox(BIGINT) FROM PUBLIC;
REVOKE ALL ON FUNCTION public.notification_user_is_sandbox(BIGINT) FROM anon;
REVOKE ALL ON FUNCTION public.notification_user_is_sandbox(BIGINT) FROM authenticated;
GRANT EXECUTE ON FUNCTION public.notification_user_is_sandbox(BIGINT) TO service_role;

-- ---------------------------------------------------------------------------
-- 4. Deposit lifecycle triggers (pending entered, confirmation committed)
-- ---------------------------------------------------------------------------

CREATE OR REPLACE FUNCTION public.notifications_capture_deposit()
RETURNS TRIGGER
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public, pg_temp
AS $$
DECLARE
    v_user_id  BIGINT;
    v_amount   NUMERIC;
    v_namespace TEXT;
    v_credited BOOLEAN := FALSE;
BEGIN
    BEGIN
        v_user_id := NEW.user_id;
        IF v_user_id IS NULL THEN
            RETURN NEW;
        END IF;

        IF TG_TABLE_NAME = 'payment_invoices' THEN
            v_namespace := 'invoice';
            v_amount := NEW.amount_usd;
        ELSE
            v_namespace := 'legacy';
            v_amount := NEW.amount;
        END IF;

        BEGIN
            v_credited := COALESCE(NEW.credited, FALSE);
        EXCEPTION WHEN OTHERS THEN
            v_credited := FALSE;
        END;

        IF public.notification_user_is_sandbox(v_user_id) THEN
            RETURN NEW;
        END IF;

        -- A deposit "enters pending": tell the customer it is being processed.
        -- The key is per deposit, so a repeated status write cannot repeat it.
        IF NEW.status = 'pending' THEN
            PERFORM public.notification_emit(
                v_user_id,
                'deposit_pending:' || v_namespace || ':' || NEW.id::text,
                'info',
                'notifications.events.depositPending.title',
                'notifications.events.depositPending.body',
                jsonb_build_object('amount', COALESCE(v_amount, 0)),
                COALESCE(NEW.created_at, now())
            );
        END IF;

        -- Confirmation only counts when the credit marker was committed in the
        -- same transaction (never on a status flip alone).
        IF NEW.status = 'confirmed' AND v_credited THEN
            PERFORM public.notification_emit(
                v_user_id,
                'deposit_confirmed:' || v_namespace || ':' || NEW.id::text,
                'success',
                'notifications.events.depositConfirmed.title',
                'notifications.events.depositConfirmed.body',
                jsonb_build_object('amount', COALESCE(v_amount, 0)),
                now()
            );
        END IF;
    EXCEPTION WHEN OTHERS THEN
        RAISE WARNING 'notifications_capture_deposit skipped (%): %', SQLSTATE, SQLERRM;
    END;
    RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS notifications_deposit_invoice ON public.payment_invoices;
CREATE TRIGGER notifications_deposit_invoice
    AFTER INSERT OR UPDATE OF status, credited ON public.payment_invoices
    FOR EACH ROW
    EXECUTE FUNCTION public.notifications_capture_deposit();

DROP TRIGGER IF EXISTS notifications_deposit_legacy ON public.deposits;
CREATE TRIGGER notifications_deposit_legacy
    AFTER INSERT OR UPDATE OF status, credited ON public.deposits
    FOR EACH ROW
    EXECUTE FUNCTION public.notifications_capture_deposit();

-- ---------------------------------------------------------------------------
-- 5. Referral reward trigger (reward actually credited to the referrer)
-- ---------------------------------------------------------------------------

CREATE OR REPLACE FUNCTION public.notifications_capture_referral()
RETURNS TRIGGER
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public, pg_temp
AS $$
DECLARE
    v_bonus NUMERIC;
BEGIN
    BEGIN
        v_bonus := COALESCE(NEW.bonus_earned, 0);

        IF NEW.status <> 'active' OR v_bonus <= 0 THEN
            RETURN NEW;
        END IF;
        IF NEW.referrer_id IS NULL THEN
            RETURN NEW;
        END IF;
        -- Self-referral and synthetic (negative) referred ids never pay.
        IF NEW.referred_id IS NOT NULL AND NEW.referred_id = NEW.referrer_id THEN
            RETURN NEW;
        END IF;
        IF COALESCE(NEW.referred_id, 0) <= 0 THEN
            RETURN NEW;
        END IF;

        IF public.notification_user_is_sandbox(NEW.referrer_id)
           OR public.notification_user_is_sandbox(NEW.referred_id) THEN
            RETURN NEW;
        END IF;

        PERFORM public.notification_emit(
            NEW.referrer_id,
            'referral:' || NEW.id::text,
            'success',
            'notifications.events.referral.title',
            'notifications.events.referral.body',
            jsonb_build_object('amount', v_bonus),
            COALESCE(NEW.updated_at, NEW.created_at, now())
        );
    EXCEPTION WHEN OTHERS THEN
        RAISE WARNING 'notifications_capture_referral skipped (%): %', SQLSTATE, SQLERRM;
    END;
    RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS notifications_referral ON public.referrals;
CREATE TRIGGER notifications_referral
    AFTER INSERT OR UPDATE OF status, bonus_earned ON public.referrals
    FOR EACH ROW
    EXECUTE FUNCTION public.notifications_capture_referral();

-- ---------------------------------------------------------------------------
-- 6. Self-check (raises -> the whole migration rolls back)
-- ---------------------------------------------------------------------------

DO $$
DECLARE
    v_missing TEXT := '';
BEGIN
    IF to_regclass('public.notifications') IS NULL THEN
        v_missing := v_missing || ' table';
    END IF;

    IF NOT EXISTS (
        SELECT 1 FROM pg_constraint c
        JOIN pg_class t ON t.oid = c.conrelid
        JOIN pg_namespace n ON n.oid = t.relnamespace
        WHERE n.nspname = 'public' AND t.relname = 'notifications'
          AND c.conname = 'notifications_user_event_key_key' AND c.contype = 'u'
    ) THEN
        v_missing := v_missing || ' unique(user_id,event_key)';
    END IF;

    IF NOT EXISTS (
        SELECT 1 FROM pg_class t
        JOIN pg_namespace n ON n.oid = t.relnamespace
        WHERE n.nspname = 'public' AND t.relname = 'notifications' AND t.relrowsecurity
    ) THEN
        v_missing := v_missing || ' rls';
    END IF;

    IF EXISTS (
        SELECT 1 FROM pg_policies p
        WHERE p.schemaname = 'public' AND p.tablename = 'notifications'
          AND 'anon' = ANY (p.roles)
    ) THEN
        v_missing := v_missing || ' anon-policy';
    END IF;

    -- Scoped to the owning table: a same-named trigger on another table must not
    -- be able to satisfy this check.
    IF to_regclass('public.payment_invoices') IS NOT NULL AND NOT EXISTS (
        SELECT 1 FROM pg_trigger
        WHERE tgname = 'notifications_deposit_invoice' AND NOT tgisinternal
          AND tgrelid = 'public.payment_invoices'::regclass
    ) THEN
        v_missing := v_missing || ' deposit-invoice-trigger';
    END IF;

    IF to_regclass('public.deposits') IS NOT NULL AND NOT EXISTS (
        SELECT 1 FROM pg_trigger
        WHERE tgname = 'notifications_deposit_legacy' AND NOT tgisinternal
          AND tgrelid = 'public.deposits'::regclass
    ) THEN
        v_missing := v_missing || ' deposit-legacy-trigger';
    END IF;

    IF to_regclass('public.referrals') IS NOT NULL AND NOT EXISTS (
        SELECT 1 FROM pg_trigger
        WHERE tgname = 'notifications_referral' AND NOT tgisinternal
          AND tgrelid = 'public.referrals'::regclass
    ) THEN
        v_missing := v_missing || ' referral-trigger';
    END IF;

    -- The server reads/updates the feed through PostgREST as service_role, and a
    -- policy alone does not grant table privileges.
    IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'service_role')
       AND NOT has_table_privilege('service_role', 'public.notifications', 'SELECT') THEN
        v_missing := v_missing || ' service-role-grant';
    END IF;

    -- Customer roles must have no access at all.
    IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'anon')
       AND has_table_privilege('anon', 'public.notifications', 'SELECT') THEN
        v_missing := v_missing || ' anon-grant';
    END IF;

    IF to_regprocedure('public.notification_emit(bigint,text,text,text,text,jsonb,timestamptz)') IS NULL THEN
        v_missing := v_missing || ' notification_emit';
    END IF;

    IF v_missing <> '' THEN
        RAISE EXCEPTION '058_notifications.sql incomplete:%', v_missing;
    END IF;

    RAISE NOTICE '058_notifications.sql applied: feed + idempotent emit + 3 observational triggers';
END $$;
