BEGIN
    IF to_regclass('public.support_conversations') IS NULL THEN v_missing := v_missing || ' table:conversations'; END IF;
    IF to_regclass('public.support_messages') IS NULL      THEN v_missing := v_missing || ' table:messages'; END IF;
    IF to_regclass('public.support_actions') IS NULL       THEN v_missing := v_missing || ' table:actions'; END IF;
    IF NOT EXISTS (SELECT 1 FROM pg_indexes WHERE schemaname = 'public' AND indexname = 'support_conversations_one_active') THEN
        v_missing := v_missing || ' index:one_active'; END IF;
    IF NOT EXISTS (SELECT 1 FROM pg_indexes WHERE schemaname = 'public' AND indexname = 'support_messages_client_dedupe') THEN
        v_missing := v_missing || ' index:client_dedupe'; END IF;
    IF NOT EXISTS (SELECT 1 FROM pg_class c JOIN pg_namespace n ON n.oid = c.relnamespace
                   WHERE n.nspname = 'public' AND c.relname = 'support_messages' AND c.relrowsecurity) THEN
        v_missing := v_missing || ' rls:messages'; END IF;
    IF EXISTS (SELECT 1 FROM pg_policies WHERE schemaname = 'public' AND tablename = 'support_messages'
               AND NOT (roles && ARRAY['service_role']::name[])) THEN
        v_missing := v_missing || ' policy:non-service-role'; END IF;
    IF to_regprocedure('public.support_post_customer_message(bigint,text,text)') IS NULL THEN
        v_missing := v_missing || ' fn:post_customer_message'; END IF;
    IF to_regprocedure('public.support_commit_ai_turn(bigint,text,text,jsonb,boolean,text)') IS NULL THEN
        v_missing := v_missing || ' fn:commit_ai_turn'; END IF;
    IF v_missing <> '' THEN
        RAISE EXCEPTION '059_native_support.sql incomplete:%', v_missing;
    END IF;
    RAISE NOTICE '059_native_support.sql applied: conversations, messages, actions (service_role only)';
END $$;
