-- ===========================================================================
-- 059_native_support.sql - in-app customer support messaging
--
-- PURPOSE
--   Conversations and messages for the NATIVE support chat shown inside
--   Arbitrix (customer widget + admin Support Inbox). This is a MESSAGING
--   system only: it never reads or writes wallets, deposits, withdrawals,
--   trades, referrals or subscriptions, and nothing here can move money.
--
-- WHAT IT CREATES
--   public.support_conversations  one thread per customer (one ACTIVE thread)
--   public.support_messages       the transcript (customer / ai / agent / system)
--   public.support_actions        append-only audit of human actions
--
-- ACCESS MODEL
--   Same as 039 / 045 / 058: the application authenticates with its own JWT and
--   talks to Postgres through the service-role client, so RLS is ENABLED and a
--   single service_role policy grants access. anon / authenticated get NOTHING
--   (no policy, no grant) - a leaked anon key cannot read a support transcript.
--
-- IDEMPOTENCY / DELIVERY
--   support_messages(client_message_id) is UNIQUE per conversation, so a
--   retried send (flaky mobile network, double tap) cannot duplicate a message.
--
-- FEATURE FLAG
--   The tables are inert until NATIVE_SUPPORT_ENABLED=true in the server; the
--   routes answer 404 while it is off. Applying this migration alone changes no
--   customer-facing behaviour.
--
-- ROLLBACK (no money data involved)
--   DROP TABLE IF EXISTS public.support_actions;
--   DROP TABLE IF EXISTS public.support_messages;
--   DROP TABLE IF EXISTS public.support_conversations;
-- ===========================================================================

-- ---------------------------------------------------------------------------
-- 1. Conversations
-- ---------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS public.support_conversations (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id             BIGINT      NOT NULL REFERENCES public.users (id) ON DELETE CASCADE,
    category            TEXT        NOT NULL DEFAULT 'general',
    status              TEXT        NOT NULL DEFAULT 'open',
    language            TEXT        NOT NULL DEFAULT 'en',
    subject             TEXT,
    -- TRUE while a human owns the thread: the AI must not answer.
    ai_paused           BOOLEAN     NOT NULL DEFAULT FALSE,
    assigned_admin_id   BIGINT      REFERENCES public.users (id) ON DELETE SET NULL,
    -- Dialogue state of the reused conversation engine (ids/flags only).
    context             JSONB       NOT NULL DEFAULT '{}'::jsonb,
    last_message_at     TIMESTAMPTZ,
    last_message_preview TEXT,
    unread_for_customer INTEGER     NOT NULL DEFAULT 0,
    unread_for_admin    INTEGER     NOT NULL DEFAULT 0,
    created_at          TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at          TIMESTAMPTZ NOT NULL DEFAULT now(),
    resolved_at         TIMESTAMPTZ
);

ALTER TABLE public.support_conversations DROP CONSTRAINT IF EXISTS support_conversations_category_check;
ALTER TABLE public.support_conversations
    ADD CONSTRAINT support_conversations_category_check
    CHECK (category IN ('deposit', 'withdrawal', 'trading', 'account', 'general'));

ALTER TABLE public.support_conversations DROP CONSTRAINT IF EXISTS support_conversations_status_check;
ALTER TABLE public.support_conversations
    ADD CONSTRAINT support_conversations_status_check
    CHECK (status IN ('open', 'assigned', 'waiting', 'resolved'));

ALTER TABLE public.support_conversations DROP CONSTRAINT IF EXISTS support_conversations_language_check;
ALTER TABLE public.support_conversations
    ADD CONSTRAINT support_conversations_language_check
    CHECK (language IN ('en', 'es', 'pt', 'fr', 'ar', 'zh'));

ALTER TABLE public.support_conversations DROP CONSTRAINT IF EXISTS support_conversations_context_check;
ALTER TABLE public.support_conversations
    ADD CONSTRAINT support_conversations_context_check
    CHECK (jsonb_typeof(context) = 'object');

ALTER TABLE public.support_conversations DROP CONSTRAINT IF EXISTS support_conversations_unread_check;
ALTER TABLE public.support_conversations
    ADD CONSTRAINT support_conversations_unread_check
    CHECK (unread_for_customer >= 0 AND unread_for_admin >= 0);

-- One ACTIVE thread per customer: the widget resumes it instead of piling up
-- duplicates; Resolve closes it and a new one may then be created.
CREATE UNIQUE INDEX IF NOT EXISTS support_conversations_one_active
    ON public.support_conversations (user_id)
    WHERE status <> 'resolved';

CREATE INDEX IF NOT EXISTS support_conversations_inbox_idx
    ON public.support_conversations (status, last_message_at DESC NULLS LAST);

CREATE INDEX IF NOT EXISTS support_conversations_user_idx
    ON public.support_conversations (user_id, last_message_at DESC NULLS LAST);

COMMENT ON TABLE public.support_conversations IS
    'Native in-app support threads. ai_paused=TRUE means a human owns the thread.';

-- ---------------------------------------------------------------------------
-- 2. Messages
-- ---------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS public.support_messages (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    conversation_id BIGINT      NOT NULL REFERENCES public.support_conversations (id) ON DELETE CASCADE,
    sender_type     TEXT        NOT NULL,
    sender_user_id  BIGINT      NULL,
    body            TEXT        NOT NULL,
    client_message_id TEXT      NULL,
    created_at      TIMESTAMPTZ NOT NULL DEFAULT now()
);

ALTER TABLE public.support_messages DROP CONSTRAINT IF EXISTS support_messages_sender_check;
ALTER TABLE public.support_messages
    ADD CONSTRAINT support_messages_sender_check
    CHECK (sender_type IN ('customer', 'ai', 'agent', 'system'));

ALTER TABLE public.support_messages DROP CONSTRAINT IF EXISTS support_messages_body_check;
ALTER TABLE public.support_messages
    ADD CONSTRAINT support_messages_body_check
    CHECK (char_length(body) BETWEEN 1 AND 4000);

CREATE UNIQUE INDEX IF NOT EXISTS support_messages_client_dedupe
    ON public.support_messages (conversation_id, client_message_id)
    WHERE client_message_id IS NOT NULL;

CREATE INDEX IF NOT EXISTS support_messages_feed_idx
    ON public.support_messages (conversation_id, id);

COMMENT ON TABLE public.support_messages IS
    'Support transcript. client_message_id is the sender-side idempotency key.';

-- ---------------------------------------------------------------------------
-- 3. Human-action audit (append-only)
-- ---------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS public.support_actions (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    conversation_id BIGINT      NOT NULL REFERENCES public.support_conversations (id) ON DELETE CASCADE,
    actor_user_id   BIGINT      NULL,
    action          TEXT        NOT NULL,
    detail          JSONB       NOT NULL DEFAULT '{}'::jsonb,
    created_at      TIMESTAMPTZ NOT NULL DEFAULT now()
);

ALTER TABLE public.support_actions DROP CONSTRAINT IF EXISTS support_actions_action_check;
ALTER TABLE public.support_actions
    ADD CONSTRAINT support_actions_action_check
    CHECK (action IN ('takeover', 'resume', 'assign', 'resolve', 'reopen', 'initiate', 'escalate', 'message'));

CREATE INDEX IF NOT EXISTS support_actions_conversation_idx
    ON public.support_actions (conversation_id, id);

-- ---------------------------------------------------------------------------
-- 4. Access control (service_role only)
-- ---------------------------------------------------------------------------
ALTER TABLE public.support_conversations ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.support_messages      ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.support_actions       ENABLE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS support_conversations_service_all ON public.support_conversations;
CREATE POLICY support_conversations_service_all ON public.support_conversations
    FOR ALL TO service_role USING (true) WITH CHECK (true);

DROP POLICY IF EXISTS support_messages_service_all ON public.support_messages;
CREATE POLICY support_messages_service_all ON public.support_messages
    FOR ALL TO service_role USING (true) WITH CHECK (true);

DROP POLICY IF EXISTS support_actions_service_all ON public.support_actions;
CREATE POLICY support_actions_service_all ON public.support_actions
    FOR ALL TO service_role USING (true) WITH CHECK (true);

REVOKE ALL ON public.support_conversations FROM PUBLIC, anon, authenticated;
REVOKE ALL ON public.support_messages      FROM PUBLIC, anon, authenticated;
REVOKE ALL ON public.support_actions       FROM PUBLIC, anon, authenticated;
GRANT ALL ON public.support_conversations TO service_role;
GRANT ALL ON public.support_messages      TO service_role;
GRANT ALL ON public.support_actions       TO service_role;

DO $$
BEGIN
    IF EXISTS (SELECT 1 FROM pg_sequences WHERE schemaname = 'public' AND sequencename = 'support_conversations_id_seq') THEN
        EXECUTE 'REVOKE ALL ON SEQUENCE public.support_conversations_id_seq FROM PUBLIC, anon, authenticated';
        EXECUTE 'GRANT USAGE, SELECT ON SEQUENCE public.support_conversations_id_seq TO service_role';
    END IF;
    IF EXISTS (SELECT 1 FROM pg_sequences WHERE schemaname = 'public' AND sequencename = 'support_messages_id_seq') THEN
        EXECUTE 'REVOKE ALL ON SEQUENCE public.support_messages_id_seq FROM PUBLIC, anon, authenticated';
        EXECUTE 'GRANT USAGE, SELECT ON SEQUENCE public.support_messages_id_seq TO service_role';
    END IF;
    IF EXISTS (SELECT 1 FROM pg_sequences WHERE schemaname = 'public' AND sequencename = 'support_actions_id_seq') THEN
        EXECUTE 'REVOKE ALL ON SEQUENCE public.support_actions_id_seq FROM PUBLIC, anon, authenticated';
        EXECUTE 'GRANT USAGE, SELECT ON SEQUENCE public.support_actions_id_seq TO service_role';
    END IF;
END $$;

-- ---------------------------------------------------------------------------
-- 5. Self-check: fail loudly (and roll back) rather than leave a half schema
-- ---------------------------------------------------------------------------
DO $$
DECLARE v_missing TEXT := '';
BEGIN
    IF to_regclass('public.support_conversations') IS NULL THEN v_missing := v_missing || ' table:conversations'; END IF;
    IF to_regclass('public.support_messages') IS NULL      THEN v_missing := v_missing || ' table:messages'; END IF;
    IF to_regclass('public.support_actions') IS NULL       THEN v_missing := v_missing || ' table:actions'; END IF;
    IF NOT EXISTS (SELECT 1 FROM pg_indexes WHERE schemaname = 'public' AND indexname = 'support_conversations_one_active') THEN
        v_missing := v_missing || ' index:one_active'; END IF;
    IF NOT EXISTS (SELECT 1 FROM pg_indexes WHERE schemaname = 'public' AND indexname = 'support_messages_client_dedupe') THEN
        v_missing := v_missing || ' index:client_dedupe'; END IF;
    IF NOT EXISTS (SELECT 1 FROM pg_class c JOIN pg_namespace n ON n.oid = c.relnamespace
                   WHERE n.nspname = 'public' AND c.relname = 'support_messages' AND c.relrowsecurity) THEN
        v_missing := v_missing || ' rls:messages'; END IF;
    IF EXISTS (SELECT 1 FROM pg_policies WHERE schemaname = 'public' AND tablename = 'support_messages'
               AND NOT (roles && ARRAY['service_role']::name[])) THEN
        v_missing := v_missing || ' policy:non-service-role'; END IF;
    IF v_missing <> '' THEN
        RAISE EXCEPTION '059_native_support.sql incomplete:%', v_missing;
    END IF;
    RAISE NOTICE '059_native_support.sql applied: conversations, messages, actions (service_role only)';
END $$;
