        EXECUTE 'REVOKE ALL ON SEQUENCE public.support_actions_id_seq FROM PUBLIC, anon, authenticated';
        EXECUTE 'GRANT USAGE, SELECT ON SEQUENCE public.support_actions_id_seq TO service_role';
    END IF;
