'use strict';

/**
 * Approved copy for the two deposit sections:
 *   1. the Verified Payment Partner panel (heading, two paragraphs, button);
 *   2. the deposit-reference box (empty state only when no deposit exists).
 *
 * Behaviour is exercised by running the real updateDepositReferenceBox() in a
 * vm sandbox, so "empty state only when no deposit was created" is proven, not
 * assumed.
 */

const { test } = require('node:test');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const vm = require('node:vm');

const INDEX = fs.readFileSync(path.join(__dirname, '..', 'public', 'index.html'), 'utf8');

const APPROVED_EN = {
    'deposit.partner.title': 'Verified Payment Partner',
    'deposit.partner.intro': 'Need help obtaining USDT for your Arbitrix deposit? Contact our Payment Partner on Telegram for payment assistance.',
    'deposit.partner.modelNote': 'The Payment Partner can guide you through obtaining USDT. You must send the USDT to the unique deposit address generated by Arbitrix. Your account is credited only after Arbitrix verifies the incoming transaction.',
    'deposit.partner.contactPaymentPartner': 'Contact Payment Partner',
    'deposit.partner.refTitle': 'Your Deposit Reference',
    'deposit.partner.refNone': 'No deposit has been created yet.',
    'deposit.partner.refHint': 'Once you generate a deposit request, your unique deposit reference and payment instructions will appear here. You can share the reference with the Payment Partner if you need assistance.',
};

function dict() {
    const tIdx = INDEX.indexOf('const TRANSLATIONS');
    let i = INDEX.indexOf('{', tIdx);
    let depth = 0, end = -1;
    for (; i < INDEX.length; i++) {
        if (INDEX[i] === '{') depth++;
        else if (INDEX[i] === '}') { depth--; if (depth === 0) { end = i; break; } }
    }
    const ctx = {};
    vm.createContext(ctx);
    vm.runInContext(INDEX.slice(tIdx, end + 1) + '; this.T = TRANSLATIONS;', ctx);
    return ctx.T;
}

function extractFunction(name) {
    const start = INDEX.indexOf('function ' + name + '(');
    assert.ok(start >= 0, name + ' should exist');
    let i = INDEX.indexOf('{', start), depth = 0, end = -1;
    for (; i < INDEX.length; i++) {
        if (INDEX[i] === '{') depth++;
        else if (INDEX[i] === '}') { depth--; if (depth === 0) { end = i; break; } }
    }
    return INDEX.slice(start, end + 1);
}

const panel = () => INDEX.slice(INDEX.indexOf('id="depositPartnerPanel"'),
    INDEX.indexOf('id="depositCryptoFlow"'));

// ------------------------------------------------------- Verified Payment Partner

test('the partner panel carries the approved English copy verbatim', () => {
    const T = dict();
    for (const [key, value] of Object.entries(APPROVED_EN)) {
        assert.strictEqual(T.en[key], value, key + ' must match the approved copy');
    }
});

test('the panel renders heading, two paragraphs and the button, in that order', () => {
    const p = panel();
    const titleAt = p.indexOf('data-i18n="deposit.partner.title"');
    const introAt = p.indexOf('data-i18n="deposit.partner.intro"');
    const noteAt = p.indexOf('data-i18n="deposit.partner.modelNote"');
    const btnAt = p.indexOf('id="depositPaymentPartnerBtn"');
    assert.ok(titleAt > 0 && introAt > 0 && noteAt > 0 && btnAt > 0, 'all four elements exist');
    assert.ok(titleAt < introAt && introAt < noteAt && noteAt < btnAt, 'heading -> paragraph -> paragraph -> button');
    // Exactly two intro paragraphs: the repetitive ones are gone.
    assert.ok(!p.includes('deposit.partner.servicesIntro'), 'servicesIntro retired');
    assert.ok(!p.includes('depositPaymentPartnerNote'), 'the redundant note beside the button is retired');
    assert.strictEqual((p.match(/data-i18n="deposit\.partner\.(intro|modelNote|servicesIntro)"/g) || []).length, 2,
        'the section explains itself in exactly two paragraphs');
});

test('the button keeps its label and its existing Telegram destination', () => {
    const p = panel();
    assert.match(p, /data-i18n="deposit\.partner\.contactPaymentPartner">Contact Payment Partner</);
    assert.strictEqual((INDEX.match(/<meta name="arbitrix-partner-support-telegram" content="([^"]*)">/) || [])[1],
        '@Arbitrix_CSA1', 'destination unchanged');
    assert.match(extractFunction('getPartnerSupportTelegramUrl'), /https:\/\/t\.me\//);
});

test('the panel does not imply the payment partner is a directory listing', () => {
    const T = dict();
    for (const locale of Object.keys(T)) {
        for (const key of ['deposit.partner.title', 'deposit.partner.intro', 'deposit.partner.modelNote']) {
            const value = String(T[locale][key]);
            assert.ok(value.trim(), locale + ' missing ' + key);
            // Verification of a directory entry is the directory's job (badge +
            // disclaimer); the heading/paragraphs must not claim membership.
            assert.ok(!/listed partner|partner listing|in our directory|directory listing/i.test(value),
                locale + ' ' + key + ' must not claim a directory listing');
            assert.ok(!/official/i.test(value), locale + ' ' + key + ' must not claim official support status');
        }
    }
    // The directory itself (cards, verified badge, disclaimer) is untouched.
    const p = panel();
    assert.ok(p.includes('id="depositPartnerList"'), 'directory list preserved');
    assert.ok(p.includes('id="depositPartnerEmpty"'), 'directory empty state preserved');
    // The badge is rendered per card by the existing renderer, not in markup.
    assert.match(extractFunction('renderDepositPartners'), /deposit\.partner\.verified/,
        'verified badge preserved');
    assert.ok(p.includes('data-i18n="deposit.partner.disclaimer"'), 'directory disclaimer preserved');
    assert.match(extractFunction('renderDepositPartners'), /deposit\.partner\.verified/,
        'the badge still comes from the existing verification logic');
});

// ------------------------------------------------------------ deposit reference

test('the deposit-reference copy is the approved empty state', () => {
    const T = dict();
    assert.strictEqual(T.en['deposit.partner.refTitle'], 'Your Deposit Reference');
    assert.strictEqual(T.en['deposit.partner.refNone'], 'No deposit has been created yet.');
    assert.match(T.en['deposit.partner.refHint'], /unique deposit reference and payment instructions will appear here/);
    assert.match(T.en['deposit.partner.refHint'], /share the reference with the Payment Partner/i);
    // The ready-state sentence is untouched.
    assert.match(T.en['deposit.partner.refReady'], /Share this reference with your partner/);
});

test('the empty state appears only when no deposit exists (real function)', () => {
    function run(invoiceId) {
        const nodes = {};
        const mk = (id) => (nodes[id] = { id, textContent: '', style: { display: '' },
            setAttribute() {}, getAttribute() { return null; }, classList: { contains: () => false } });
        const valueEl = mk('depositRefValue');
        const hintEl = mk('depositRefHint');
        const copyBtn = mk('depositRefCopyBtn');
        const sandbox = {
            currentInvoiceId: invoiceId,
            depositOptionState: { crypto: { asset: 'USDT', network: 'TRC20' } },
            document: { getElementById: (id) => nodes[id] || null },
            t: (k, vars) => k + JSON.stringify(vars || {}),
            console: { log() {}, warn() {}, error() {} },
        };
        vm.createContext(sandbox);
        vm.runInContext('function updateDepositReferenceBox()' +
            extractFunction('updateDepositReferenceBox').slice('function updateDepositReferenceBox()'.length) +
            '\nupdateDepositReferenceBox();', sandbox);
        return { value: valueEl.textContent, hint: hintEl.textContent, copy: copyBtn.style.display };
    }

    const empty = run(null);
    assert.strictEqual(empty.value, 'deposit.partner.refNone{}', 'empty state when no deposit exists');
    assert.match(empty.hint, /^deposit\.partner\.refHint/, 'empty hint shown only here');
    assert.strictEqual(empty.copy, 'none', 'nothing to copy before a deposit exists');

    const ready = run('inv_abc123');
    assert.strictEqual(ready.value, 'inv_abc123', 'the real reference is shown');
    assert.match(ready.hint, /^deposit\.partner\.refReady/, 'ready guidance replaces the empty state');
    assert.ok(!/refNone|refHint/.test(ready.value + ready.hint), 'empty copy never leaks into the ready state');
    assert.strictEqual(ready.copy, 'inline-flex', 'copy action returns with a reference');
});

// ------------------------------------------------------------------- i18n + scope

test('all six locales carry both sections and differ from English', () => {
    const T = dict();
    assert.deepStrictEqual(Object.keys(T).sort(), ['ar', 'en', 'es', 'fr', 'pt', 'zh']);
    const keys = Object.keys(APPROVED_EN);
    const sizes = Object.keys(T).map((l) => Object.keys(T[l]).length);
    assert.strictEqual(new Set(sizes).size, 1, 'identical key counts');
    for (const locale of Object.keys(T)) {
        for (const key of keys) {
            assert.ok(String(T[locale][key] || '').trim(), locale + ' missing ' + key);
            if (locale !== 'en') {
                assert.notStrictEqual(T[locale][key], T.en[key], locale + ' ' + key + ' is still English');
            }
        }
    }
});

